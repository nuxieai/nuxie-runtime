#!/usr/bin/env python3
"""Generate CSS titlecase exceptions from CPython's built-in Unicode database.

CPython's full titlecase mappings combine UnicodeData.txt's simple titlecase
field with SpecialCasing.txt's unconditional title mappings. A single character's
str.title() returns that full default mapping without language tailoring.

Run with a Python built with Unicode 16.0.0. No downloads or packages are needed.
"""

from pathlib import Path
import unicodedata


UNICODE_VERSION = "16.0.0"
OUTPUT = (
    Path(__file__).resolve().parents[2]
    / "crates/nuxie-runtime/src/css_titlecase_data.rs"
)


def rust_escape(value):
    return "".join(f"\\u{{{ord(char):x}}}" for char in value)


def main():
    if unicodedata.unidata_version != UNICODE_VERSION:
        raise SystemExit(f"requires Python Unicode data {UNICODE_VERSION}")
    rows = [
        "// Generated by tools/unicode/generate_titlecase.py.\n",
        "// Unicode 16.0.0: UnicodeData.txt titlecase and unconditional\n",
        "// SpecialCasing.txt title mappings, from CPython's built-in database.\n",
        "// Only mappings that differ from full uppercase are stored.\n",
        "pub(super) const TITLECASE_EXCEPTIONS: &[(char, &str)] = &[\n",
    ]
    for code_point in range(0x110000):
        char = chr(code_point)
        title = char.title()
        if title != char.upper():
            rows.append(f'    (\'{rust_escape(char)}\', "{rust_escape(title)}"),\n')
    rows.append("];\n")
    OUTPUT.write_text("".join(rows), encoding="utf-8")


if __name__ == "__main__":
    main()
