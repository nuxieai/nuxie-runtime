#!/usr/bin/env python3
"""Writes the pairs-order differential cases (tests/luau-vm-diff/pairs_order_*.luau).

docs/luau-safe-vm-pairs-order.md, section 4.1: a seeded generator emits
scripts that apply random sequences of the operations in section 3.3 to
tables keyed by strings (lengths 0 to 200, so both branches of the string
hash run), numbers (integers, fractions, negatives, large, -0), booleans and
vectors, and mixes of them. After each step a script prints the full `pairs`
order and `next` from each key. The seed is fixed and the output committed,
so the corpus is a fixed set, not a fuzzer: change the generator and rerun
it rather than editing the cases.

    python3 tools/luau-vm-diff/gen_pairs_order_cases.py

Each file holds TABLES_PER_FILE tables; each table prints lines prefixed
with its label (`T<file>.<n>`), so a disagreement can be reduced to one
table.
"""

import random
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "tests" / "luau-vm-diff"
SEED = 20261113
FILES = 40
TABLES_PER_FILE = 15
ALPHABET = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_"

HEADER = """\
-- Generated by tools/luau-vm-diff/gen_pairs_order_cases.py (seed @SEED@,
-- file @INDEX@); do not edit. Prints hash-part iteration order on purpose:
-- the safe VM matches the vendored VM's order for value-typed keys
-- (docs/luau-safe-vm-pairs-order.md).
local function show(x)
  local ty = type(x)
  if ty == "string" then
    if #x <= 16 then return "'" .. x .. "'" end
    return "'" .. string.sub(x, 1, 8) .. "~" .. #x .. "~" .. string.sub(x, -4) .. "'"
  elseif ty == "number" then
    if x == 0 and 1 / x < 0 then return "-0" end
    return string.format("%.17g", x)
  elseif ty == "vector" then
    return string.format("<%.9g,%.9g,%.9g>", x.x, x.y, x.z)
  elseif ty == "table" then
    return "tbl" .. tostring(rawget(x, "id"))
  end
  return tostring(x)
end
local function dump(label, t)
  local order = {}
  for k, v in pairs(t) do order[#order + 1] = show(k) .. "=" .. show(v) end
  print(label, #order, table.concat(order, " "))
  local nexts = {}
  for k in pairs(t) do nexts[#nexts + 1] = show((next(t, k))) end
  print(label, "next", table.concat(nexts, " "))
end
"""


def lua_str(s):
    return '"' + s + '"'


def rand_string(rng):
    roll = rng.random()
    if roll < 0.05:
        n = 0
    elif roll < 0.6:
        n = rng.randint(1, 12)
    elif roll < 0.85:
        n = rng.randint(13, 31)
    else:
        n = rng.randint(32, 200)
    return "".join(rng.choice(ALPHABET) for _ in range(n))


def rand_number(rng):
    roll = rng.randrange(10)
    if roll == 0:
        return str(rng.randint(1, 40))
    if roll == 1:
        return str(rng.randint(-1000, 0))
    if roll == 2:
        return str(rng.randint(41, 100000))
    if roll == 3:
        return repr(round(rng.uniform(-1000, 1000), rng.randint(1, 6)))
    if roll == 4:
        return rng.choice(["-0", "0", "0.5", "-0.5", "1/3", "2^31", "-2^31", "2^32", "2^53",
                           "2^53 + 1", "1e300", "-1e300", "math.huge", "-math.huge",
                           "2^-1074", "1e-300", "math.pi"])
    if roll == 5:
        return str(rng.randint(1, 8) * 1024)
    if roll == 6:
        return repr(rng.randint(1, 64) + 0.25)
    if roll == 7:
        return str(-rng.randint(1, 64))
    if roll == 8:
        return str(rng.randint(2 ** 31, 2 ** 52))
    return repr(rng.uniform(-1e12, 1e12))


def rand_vector(rng):
    def comp():
        roll = rng.randrange(6)
        if roll == 0:
            return "0"
        if roll == 1:
            return "-0"
        if roll == 2:
            return str(rng.randint(-8, 8))
        return repr(round(rng.uniform(-100, 100), rng.randint(0, 4)))
    return "vector.create(%s, %s, %s)" % (comp(), comp(), comp())


def key_pool(rng, kind):
    n = rng.choice([1, 2, 3, 5, 8, 12, 17, 25, 33, 48, 70])
    pool = []
    for _ in range(n):
        k = kind if kind != "mixed" else rng.choice(["string", "string", "number", "boolean", "vector"])
        if k == "string":
            pool.append(lua_str(rand_string(rng)))
        elif k == "number":
            pool.append(rand_number(rng))
        elif k == "boolean":
            pool.append(rng.choice(["true", "false"]))
        else:
            pool.append(rand_vector(rng))
    # Keep the first spelling of each key (duplicates collapse in Lua anyway).
    seen, out = set(), []
    for k in pool:
        if k not in seen:
            seen.add(k)
            out.append(k)
    return out


def literal_key(k):
    return "[" + k + "]"


def gen_table(rng, label, out):
    kind = rng.choice(["string", "string", "string", "number", "boolean", "vector", "mixed", "mixed"])
    keys = key_pool(rng, kind)
    weak = kind != "number" and rng.random() < 0.08
    w = out.append
    # A full collection: in a weak table's block, after `scrub` (below).
    collect = "scrub() collectgarbage()" if weak else "collectgarbage()"
    w("do")
    w("  local keys = {" + ", ".join(keys) + "}")
    w("  local vals = 0")
    w("  local function val() vals += 1 return vals end")
    # Creation.
    create = rng.choice(["empty", "empty", "literal", "literal_const", "hint", "clone", "create", "weak"] if weak
                        else ["empty", "empty", "literal", "literal_const", "hint", "clone", "create"])
    if weak:
        create = "weak"
    if create == "literal" or create == "literal_const":
        chosen = keys[: rng.randint(0, len(keys))]
        # String keys that are identifiers compile to the `DUPTABLE` template
        # path when every value is a constant (`literal_const`).
        if create == "literal_const":
            items = [literal_key(k) + " = " + str(i + 1) for i, k in enumerate(chosen)]
        else:
            items = [literal_key(k) + " = val()" for k in chosen]
        w("  local t = {" + ", ".join(items) + "}")
        if create == "literal_const":
            w("  vals = %d" % len(chosen))
    elif create == "hint":
        # A shape with named fields, so the compiler sizes the hash part.
        names = ["f%d" % i for i in range(rng.randint(1, 9))]
        w("  local t = {" + ", ".join("%s = val()" % n for n in names) + "}")
    elif create == "clone":
        chosen = keys[: rng.randint(0, len(keys))]
        w("  local src = {}")
        w("  for i = 1, %d do src[keys[i]] = val() end" % len(chosen))
        w("  local t = table.clone(src)")
    elif create == "create":
        w("  local t = table.create(%d, 0)" % rng.randint(0, 6))
    elif create == "weak":
        mode = rng.choice(["v", "vs", "kv", "kvs"])
        w('  local t = setmetatable({}, {__mode = "%s"})' % mode)
        w("  local hold = {}")
        # Collectable values are made in a callee whose stack slots `scrub`
        # then overwrites, so no stale register keeps one alive: C++ marks
        # a running frame's whole register window, stale slots included,
        # and which entries survive a collection must not depend on that.
        w("  local function put(i, keep) local v = {id = val()} t[keys[i]] = v if keep then hold[#hold + 1] = v end end")
        w("  local function scrub() " + " ".join("local s%d = false" % n for n in range(64)) + " end")
    else:
        w("  local t = {}")
    w('  dump("%s.0", t)' % label)
    steps = rng.randint(3, 9)
    for step in range(1, steps + 1):
        op = rng.choice(["insert", "insert", "insert", "delete", "reinsert", "array", "clear",
                         "clone", "move", "freeze_read", "weak_gc"] if create == "weak"
                        else ["insert", "insert", "insert", "delete", "reinsert", "array", "clear",
                              "clone", "move", "freeze_read"])
        if op == "insert":
            lo = rng.randint(1, len(keys))
            hi = rng.randint(lo, len(keys))
            if create == "weak":
                w("  for i = %d, %d do put(i, i %% 2 == 0) end %s" % (lo, hi, collect))
            else:
                w("  for i = %d, %d do t[keys[i]] = val() end" % (lo, hi))
        elif op == "delete":
            i = rng.randint(1, len(keys))
            # `next` from the dead key is valid until the table rehashes.
            # C++'s collector turns an emptied node's collectable key into a
            # dead key, which a reinsert passes by; collecting right after
            # the delete keeps the order independent of collector timing.
            w("  if t[keys[%d]] ~= nil then t[keys[%d]] = nil print(\"%s.%d dead\", show((next(t, keys[%d])))) %s end"
              % (i, i, label, step, i, collect))
            if rng.random() < 0.5:
                j = rng.randint(1, len(keys))
                w(("  put(%d, true) " + collect if create == "weak" else "  t[keys[%d]] = val()") % j)
        elif op == "reinsert":
            i = rng.randint(1, len(keys))
            w("  t[keys[%d]] = nil %s" % (i, collect))
            w(("  put(%d, false) " + collect if create == "weak" else "  t[keys[%d]] = val()") % i)
        elif op == "array":
            # Integer keys that move between the array part and the hash part.
            lo = rng.randint(1, 20)
            hi = lo + rng.randint(0, 20)
            stride = rng.choice([1, 1, 2, 3])
            if rng.random() < 0.5:
                w("  for i = %d, %d, %d do t[i] = val() end" % (lo, hi, stride))
            else:
                w("  for i = %d, %d, -%d do t[i] = val() end" % (hi, lo, stride))
            if rng.random() < 0.3:
                w("  for i = %d, %d do t[i] = nil end" % (lo, hi))
        elif op == "clear":
            w("  table.clear(t)")
            lo = rng.randint(1, len(keys))
            w("  for i = %d, %d do %s end" % (lo, len(keys), "put(i, i % 3 == 0)" if create == "weak" else "t[keys[i]] = val()"))
            if create == "weak":
                w("  " + collect)
        elif op == "clone":
            if create == "weak":
                continue
            w("  t = table.clone(t)")
            w("  t[keys[%d]] = val()" % rng.randint(1, len(keys)))
        elif op == "move":
            if create == "weak":
                continue
            a = rng.randint(1, 5)
            e = a + rng.randint(0, 6)
            dst = rng.choice([1, 3, 10, 100, 1000])
            w("  do local src = {} for i = %d, %d do src[i] = val() end table.move(src, %d, %d, %d, t) end" % (a, e, a, e, dst))
        elif op == "freeze_read":
            if create == "weak":
                continue
            w("  t = table.clone(table.freeze(table.clone(t)))")
        elif op == "weak_gc":
            w("  if #hold > 0 and %s then table.remove(hold, 1) end" % ("true" if rng.random() < 0.6 else "false"))
            w("  " + collect)
        w('  dump("%s.%d", t)' % (label, step))
    w("end")


def main():
    rng = random.Random(SEED)
    for old in OUT.glob("pairs_order_gen_*.luau"):
        old.unlink()
    for index in range(FILES):
        lines = [HEADER.replace("@SEED@", str(SEED)).replace("@INDEX@", str(index)).rstrip("\n")]
        for n in range(TABLES_PER_FILE):
            gen_table(rng, "T%d.%d" % (index, n), lines)
        (OUT / ("pairs_order_gen_%02d.luau" % index)).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
